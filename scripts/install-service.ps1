<#
.SYNOPSIS
    Register the two LadderStock scheduled tasks (API + watchdog) and generate
    the unprivileged restart helper.

.DESCRIPTION
    QUOT-443 / DEC-063. Creates:

      * "LadderStock API"      -> python -m ladderstock.cli.main run
      * "LadderStock Watchdog"  -> python -m ladderstock.cli.main watchdog
                                   --restart-task "LadderStock API"
                                   --restart-script <LOCALAPPDATA>\LadderStock\restart-api.ps1

    Both tasks use the S4U principal / hidden / boot-trigger settings already
    proven by the existing "\Vibe AStock API" task. NOTE: Windows Task Scheduler
    rejects a restart interval shorter than one minute (the reference task
    \Vibe AStock API also uses PT1M), so the watchdog uses PT1M.

    The generated restart helper only stops the *exact PID recorded by the
    watchdog* and only when that PID still owns port 5950. It never kills by
    image name and refuses anything named multica*.

    Registration needs an elevated shell. This script is safe to run without
    elevation: it still generates the restart helper, then reports the exact
    command an administrator has to run once.

.EXAMPLE
    powershell -NoProfile -ExecutionPolicy Bypass -File .\scripts\install-service.ps1
#>

[CmdletBinding()]
param(
    [string]$ApiTaskName = 'LadderStock API',
    [string]$WatchdogTaskName = 'LadderStock Watchdog',
    [int]$ApiPort = 5950
)

$ErrorActionPreference = 'Stop'

function Write-Step([string]$Message) {
    Write-Host "[ldst] $Message"
}

# --------------------------------------------------------------------------- #
# Resolve paths
# --------------------------------------------------------------------------- #

$RepoRoot = Split-Path -Parent $PSScriptRoot
if (-not (Test-Path -LiteralPath (Join-Path $RepoRoot 'pyproject.toml'))) {
    throw "Repository root not found (expected pyproject.toml next to scripts/): $RepoRoot"
}

$Python = ''
$VenvPython = Join-Path $RepoRoot '.venv\Scripts\python.exe'
if (Test-Path -LiteralPath $VenvPython) {
    $Python = $VenvPython
} else {
    $command = Get-Command python -ErrorAction SilentlyContinue
    if ($command) { $Python = $command.Source }
}
if (-not $Python) {
    throw 'python.exe not found. Activate the project virtualenv or add Python to PATH.'
}

# The tasks call `python -m ladderstock.cli.main`; the package must be installed
# in that interpreter (`pip install -e ".[all]"`). Warn instead of failing so the
# restart helper is still generated for inspection.
try {
    & $Python -c 'import ladderstock' 2>$null
    if ($LASTEXITCODE -ne 0) { throw 'import failed' }
} catch {
    Write-Warning "python cannot import ladderstock. Run: `"$Python`" -m pip install -e `"$RepoRoot`""
}

# Same precedence as ladderstock.cli.paths.data_dir()（DEC-071）
# 安装态落点由 platformdirs 决定：Windows 上 user_data_dir("LadderStock","QuotaFuse")
# 即 %LOCALAPPDATA%\QuotaFuse\LadderStock\data，不再假设 ~\.ladderstock。
$DataDir = ''
if ($env:LDST_DATA_DIR) {
    $DataDir = $env:LDST_DATA_DIR
} elseif (Test-Path -LiteralPath (Join-Path $RepoRoot 'data')) {
    $DataDir = Join-Path $RepoRoot 'data'
} else {
    $DataDir = Join-Path (Join-Path (Join-Path $env:LOCALAPPDATA 'QuotaFuse') 'LadderStock') 'data'
}
$StateDir = Join-Path $DataDir 'state'
New-Item -ItemType Directory -Path $StateDir -Force | Out-Null

$HelperDir = Join-Path $env:LOCALAPPDATA 'LadderStock'
New-Item -ItemType Directory -Path $HelperDir -Force | Out-Null
$RestartScript = Join-Path $HelperDir 'restart-api.ps1'

# --------------------------------------------------------------------------- #
# Generate the unprivileged restart helper
# --------------------------------------------------------------------------- #

$helper = @'
# LadderStock API restart helper (generated by scripts/install-service.ps1).
# Contract (QUOT-443 / DEC-063):
#   1. stop ONLY the PID recorded in state/watchdog.json, and only when that
#      exact PID still owns the API port; never kill by image name;
#   2. start `python -m ladderstock.cli.main run` again from the repo root.
$ErrorActionPreference = 'SilentlyContinue'

$StatePath = '__STATE_PATH__'
$RepoRoot  = '__REPO_ROOT__'
$Python    = '__PYTHON__'
$ApiPort   = __API_PORT__

$pidToStop = 0
if (Test-Path -LiteralPath $StatePath) {
    try {
        $state = Get-Content -LiteralPath $StatePath -Raw -Encoding UTF8 | ConvertFrom-Json
        if ($state -and $state.api -and $state.api.pid) { $pidToStop = [int]$state.api.pid }
    } catch { $pidToStop = 0 }
}

# netstat instead of Get-NetTCPConnection: the latter takes tens of seconds on
# machines with many sockets, and the watchdog aborts the call after 30s.
function Get-PortOwner([int]$Port) {
    foreach ($line in (netstat -ano -p TCP)) {
        $parts = $line.Trim() -split '\s+'
        if ($parts.Count -lt 5 -or $parts[0] -ne 'TCP' -or $parts[3] -ne 'LISTENING') { continue }
        if ($parts[1].EndsWith(":$Port")) { return [int]$parts[4] }
    }
    return 0
}

if ($pidToStop -gt 0) {
    $proc = Get-Process -Id $pidToStop -ErrorAction SilentlyContinue
    if ($proc -and $proc.ProcessName -notlike 'multica*') {
        if ((Get-PortOwner $ApiPort) -eq $pidToStop) {
            Stop-Process -Id $pidToStop -Force -ErrorAction SilentlyContinue
            Start-Sleep -Milliseconds 800
        }
    }
}

if (-not $env:LDST_DATA_DIR) {
    $env:LDST_DATA_DIR = Split-Path -Parent (Split-Path -Parent $StatePath)
}
$env:PYTHONPATH = Join-Path $RepoRoot 'src'
$LogDir = Join-Path $env:LOCALAPPDATA 'LadderStock'
New-Item -ItemType Directory -Path $LogDir -Force | Out-Null
Start-Process -FilePath $Python `
    -ArgumentList @('-X', 'utf8', '-m', 'ladderstock.cli.main', 'run', '--port', "$ApiPort") `
    -WorkingDirectory $RepoRoot -WindowStyle Hidden `
    -RedirectStandardOutput (Join-Path $LogDir 'api.out.log') `
    -RedirectStandardError (Join-Path $LogDir 'api.err.log')
'@

$helper = $helper.
    Replace('__STATE_PATH__', (Join-Path $StateDir 'watchdog.json')).
    Replace('__REPO_ROOT__', $RepoRoot).
    Replace('__PYTHON__', $Python).
    Replace('__API_PORT__', "$ApiPort")

$utf8Bom = New-Object System.Text.UTF8Encoding($true)
[System.IO.File]::WriteAllText($RestartScript, $helper, $utf8Bom)
Write-Step "restart helper: $RestartScript"

# --------------------------------------------------------------------------- #
# Register the two tasks (S4U, hidden, boot trigger, restart on failure)
# --------------------------------------------------------------------------- #

function Test-Admin {
    $identity = [Security.Principal.WindowsIdentity]::GetCurrent()
    $principal = New-Object Security.Principal.WindowsPrincipal($identity)
    return $principal.IsInRole([Security.Principal.WindowsBuiltInRole]::Administrator)
}

$apiArguments = "-X utf8 -m ladderstock.cli.main run --port $ApiPort"
# QUOT-589 重修：看门狗无端口化（自愈监控器，不监听任何端口），不再传 --port。
$watchdogArguments = "-X utf8 -m ladderstock.cli.main watchdog" +
    " --restart-task `"$ApiTaskName`" --restart-script `"$RestartScript`""

$principal = New-ScheduledTaskPrincipal -UserId "$env:USERDOMAIN\$env:USERNAME" `
    -LogonType S4U -RunLevel Highest
$trigger = New-ScheduledTaskTrigger -AtStartup
$settings = New-ScheduledTaskSettingsSet `
    -AllowStartIfOnBatteries -DontStopIfGoingOnBatteries `
    -ExecutionTimeLimit ([TimeSpan]::Zero) `
    -Hidden -StartWhenAvailable `
    -RestartCount 999 -RestartInterval (New-TimeSpan -Minutes 1) `
    -MultipleInstances IgnoreNew

$tasks = @(
    @{ Name = $ApiTaskName; Arguments = $apiArguments },
    @{ Name = $WatchdogTaskName; Arguments = $watchdogArguments }
)

if (-not (Test-Admin)) {
    Write-Step 'NOT elevated: task registration skipped.'
    Write-Step 'An administrator must run the following ONCE:'
    Write-Host ''
    Write-Host "  powershell -NoProfile -ExecutionPolicy Bypass -File `"$PSCommandPath`""
    Write-Host ''
    Write-Step 'Until then, run the two processes manually:'
    Write-Host "  $Python $apiArguments"
    Write-Host "  $Python $watchdogArguments"
    exit 2
}

foreach ($task in $tasks) {
    $action = New-ScheduledTaskAction -Execute $Python `
        -Argument $task.Arguments -WorkingDirectory $RepoRoot
    Register-ScheduledTask -TaskName $task.Name -Action $action -Trigger $trigger `
        -Principal $principal -Settings $settings `
        -Description 'LadderStock local API / watchdog (QUOT-443 / DEC-063)' `
        -Force | Out-Null
    Write-Step "registered: $($task.Name)"
}

Write-Step "health: http://127.0.0.1:$ApiPort/api/health"
Write-Step 'watchdog: portless self-heal monitor (QUOT-589) — no HTTP endpoint'
Write-Step 'Start now: schtasks /run /tn "LadderStock API"; schtasks /run /tn "LadderStock Watchdog"'
